"""
Man-made debris target geometries.

Each target exposes the same interface as NetTarget:

    reflectivity(along_m, ground_m) -> 0..1
    height(along_m, ground_m)       -> metres
    describe()                      -> dict of ground truth

so the forward model can render any of them without special-casing.

The classes here are deliberately GEOMETRIC, not material. Sonar
measures shape, relief and acoustic hardness; it cannot measure what a
thing is made of. A drum and a plastic barrel of the same dimensions
are the same object to this system, and the system says so.

`NaturalRock` is included as the negative class. It is generated by the
same machinery as the debris so that the signature tests are compared
on equal footing rather than against a straw man.
"""

from dataclasses import dataclass, field
import numpy as np


# --------------------------------------------------------------- cylinder

@dataclass
class CylinderTarget:
    """Drum, barrel, tyre, buoy. Signature: circular symmetry."""

    centre_along_m: float
    centre_ground_m: float
    radius_m: float = 0.30
    length_m: float = 0.90          # axis length; ~0 for a tyre lying flat
    axis_rad: float = 0.0           # orientation of the cylinder axis
    upright: bool = False           # standing on end -> circular footprint
    seed: int = 0

    _rng: np.random.Generator = field(init=False, repr=False)

    def __post_init__(self):
        self._rng = np.random.default_rng(self.seed)

    def _to_local(self, along_m, ground_m):
        du = along_m - self.centre_along_m
        dv = ground_m - self.centre_ground_m
        c, s = np.cos(-self.axis_rad), np.sin(-self.axis_rad)
        return du * c - dv * s, du * s + dv * c

    def _footprint(self, u, v):
        if self.upright:
            r = np.sqrt(u ** 2 + v ** 2) / self.radius_m
            return np.clip(1.0 - r ** 6, 0.0, 1.0)
        # lying down: capsule footprint
        half = max(self.length_m / 2.0 - self.radius_m, 0.0)
        du = np.clip(np.abs(u) - half, 0.0, None)
        r = np.sqrt(du ** 2 + v ** 2) / self.radius_m
        return np.clip(1.0 - r ** 6, 0.0, 1.0)

    def reflectivity(self, along_m, ground_m):
        u, v = self._to_local(along_m, ground_m)
        fp = self._footprint(u, v)
        # a curved metal surface returns a bright specular band along its crest
        crest = np.exp(-(v / (0.45 * self.radius_m)) ** 2)
        return np.clip(fp * (0.55 + 0.75 * crest), 0.0, 1.0)

    def height(self, along_m, ground_m):
        u, v = self._to_local(along_m, ground_m)
        fp = self._footprint(u, v)
        if self.upright:
            return self.length_m * (fp > 0.02)
        # semicircular cross-section
        z = np.clip(1.0 - (v / self.radius_m) ** 2, 0.0, 1.0)
        return self.radius_m * np.sqrt(z) * (fp > 0.02)

    def describe(self):
        return {"class": "CYLINDRICAL_OBJECT",
                "expected_signature": "circularity",
                "radius_m": round(self.radius_m, 3),
                "length_m": round(self.length_m, 3),
                "upright": self.upright,
                "centre_ground_m": round(self.centre_ground_m, 2),
                "centre_along_m": round(self.centre_along_m, 2)}


# -------------------------------------------------------------------- box

@dataclass
class BoxTarget:
    """Container, crate, machinery housing. Signature: right angles."""

    centre_along_m: float
    centre_ground_m: float
    length_m: float = 2.4
    width_m: float = 1.2
    height_m: float = 1.0
    orientation_rad: float = 0.0
    seed: int = 0

    def _to_local(self, along_m, ground_m):
        du = along_m - self.centre_along_m
        dv = ground_m - self.centre_ground_m
        c, s = np.cos(-self.orientation_rad), np.sin(-self.orientation_rad)
        return du * c - dv * s, du * s + dv * c

    def _footprint(self, u, v):
        # high exponent -> sharp corners, which is the whole point
        a = np.clip(1.0 - (np.abs(u) / (self.length_m / 2)) ** 14, 0, 1)
        b = np.clip(1.0 - (np.abs(v) / (self.width_m / 2)) ** 14, 0, 1)
        return a * b

    def reflectivity(self, along_m, ground_m):
        u, v = self._to_local(along_m, ground_m)
        fp = self._footprint(u, v)
        # flat faces return strongly and evenly
        return np.clip(fp * 0.95, 0.0, 1.0)

    def height(self, along_m, ground_m):
        u, v = self._to_local(along_m, ground_m)
        return self.height_m * (self._footprint(u, v) > 0.4)

    def describe(self):
        return {"class": "ANGULAR_STRUCTURE",
                "expected_signature": "angularity",
                "length_m": round(self.length_m, 2),
                "width_m": round(self.width_m, 2),
                "height_m": round(self.height_m, 2),
                "centre_ground_m": round(self.centre_ground_m, 2),
                "centre_along_m": round(self.centre_along_m, 2)}


# ----------------------------------------------------------------- linear

@dataclass
class LinearTarget:
    """Cable, chain, pipe, mooring line. Signature: linearity."""

    centre_along_m: float
    centre_ground_m: float
    length_m: float = 8.0
    thickness_m: float = 0.12
    orientation_rad: float = 0.0
    sag: float = 0.05               # 0 = perfectly straight (pipe)
    seed: int = 0

    def _to_local(self, along_m, ground_m):
        du = along_m - self.centre_along_m
        dv = ground_m - self.centre_ground_m
        c, s = np.cos(-self.orientation_rad), np.sin(-self.orientation_rad)
        return du * c - dv * s, du * s + dv * c

    def reflectivity(self, along_m, ground_m):
        u, v = self._to_local(along_m, ground_m)
        # gentle curvature so it is not an artificial perfect line
        v = v - self.sag * self.length_m * (u / max(self.length_m, 1e-6)) ** 2
        core = np.clip(1.0 - (np.abs(v) / (self.thickness_m / 2)) ** 2, 0, 1)
        extent = np.clip(1.0 - (np.abs(u) / (self.length_m / 2)) ** 8, 0, 1)
        return np.clip(core * extent, 0.0, 1.0)

    def height(self, along_m, ground_m):
        return self.thickness_m * (self.reflectivity(along_m, ground_m) > 0.3)

    def describe(self):
        return {"class": "LINEAR_STRUCTURE",
                "expected_signature": "linearity",
                "length_m": round(self.length_m, 2),
                "thickness_m": round(self.thickness_m, 3),
                "orientation_deg": round(np.degrees(self.orientation_rad), 1),
                "centre_ground_m": round(self.centre_ground_m, 2),
                "centre_along_m": round(self.centre_along_m, 2)}


# ------------------------------------------------------------------- rock

@dataclass
class NaturalRock:
    """
    Negative class. Irregular, aperiodic, no straight edges, no corners.

    Generated with correlated random boundary perturbation so it has the
    lumpy, self-similar outline of a real rock rather than an ellipse.
    """

    centre_along_m: float
    centre_ground_m: float
    radius_m: float = 0.8
    height_m: float = 0.7
    roughness: float = 0.45
    seed: int = 0

    _coef: np.ndarray = field(init=False, repr=False)

    def __post_init__(self):
        rng = np.random.default_rng(self.seed)
        # random Fourier boundary: many modes, no dominant one
        self._coef = rng.normal(0, 1, size=(6, 2)) * self.roughness

    def _radius_at(self, theta):
        r = np.ones_like(theta)
        for k in range(self._coef.shape[0]):
            n = k + 2
            r = r + (self._coef[k, 0] * np.cos(n * theta)
                     + self._coef[k, 1] * np.sin(n * theta)) / (n ** 1.3)
        return np.clip(r, 0.35, 1.9)

    def _footprint(self, along_m, ground_m):
        du = along_m - self.centre_along_m
        dv = ground_m - self.centre_ground_m
        theta = np.arctan2(dv, du)
        rr = np.sqrt(du ** 2 + dv ** 2) / self.radius_m
        return np.clip(1.0 - (rr / self._radius_at(theta)) ** 4, 0.0, 1.0)

    def reflectivity(self, along_m, ground_m):
        fp = self._footprint(along_m, ground_m)
        return np.clip(fp ** 0.7 * 0.85, 0.0, 1.0)

    def height(self, along_m, ground_m):
        return self.height_m * self._footprint(along_m, ground_m) ** 0.6

    def describe(self):
        return {"class": "NATURAL_ROCK",
                "expected_signature": "irregularity",
                "radius_m": round(self.radius_m, 2),
                "height_m": round(self.height_m, 2),
                "centre_ground_m": round(self.centre_ground_m, 2),
                "centre_along_m": round(self.centre_along_m, 2)}
